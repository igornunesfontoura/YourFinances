package io.github.igornunesfontoura.yourfinances.data.repository

import androidx.room.withTransaction
import io.github.igornunesfontoura.yourfinances.data.db.AppDatabase
import io.github.igornunesfontoura.yourfinances.data.db.entity.RecurrenceSkipEntity
import io.github.igornunesfontoura.yourfinances.data.db.entity.toDomain
import io.github.igornunesfontoura.yourfinances.data.db.entity.toEntity
import io.github.igornunesfontoura.yourfinances.domain.model.Entry
import io.github.igornunesfontoura.yourfinances.domain.model.Recurrence
import io.github.igornunesfontoura.yourfinances.domain.recurrence.PredictionWindow
import io.github.igornunesfontoura.yourfinances.domain.recurrence.carrySlotsFrom
import io.github.igornunesfontoura.yourfinances.domain.recurrence.predictedEntriesBetween
import io.github.igornunesfontoura.yourfinances.domain.recurrence.withValuesFrom
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map
import java.time.LocalDate

/**
 * Recurrence templates and the predicted entries they keep inside the [PredictionWindow].
 * Confirmed entries are history: no operation here changes or deletes them.
 */
interface RecurrenceRepository {
    fun observeAll(): Flow<List<Recurrence>>

    suspend fun getById(id: Long): Recurrence?

    /** Stores the template and predicts its occurrences in [window]. */
    suspend fun add(recurrence: Recurrence, window: PredictionWindow): Long

    /**
     * Updates the template, rebuilds its predicted entries in [window] and drops predicted entries
     * of any month that now falls outside its start/end dates.
     */
    suspend fun update(recurrence: Recurrence, window: PredictionWindow)

    /**
     * Removes the template and its predicted entries from [window] on. Earlier predicted entries
     * stay, since they may have happened without being confirmed.
     */
    suspend fun delete(recurrence: Recurrence, window: PredictionWindow)

    /**
     * "Aplicar às próximas": saves [entry] (an edited occurrence), copies its values to the
     * template and rebuilds the predicted entries after it. If the template was deleted in the
     * meantime, only the entry is saved.
     */
    suspend fun applyToUpcoming(entry: Entry, window: PredictionWindow)

    /** Tops up predicted entries of every template in [window]; returns how many were created. */
    suspend fun predictAll(window: PredictionWindow): Int
}

class RoomRecurrenceRepository(private val database: AppDatabase) : RecurrenceRepository {
    private val recurrenceDao = database.recurrenceDao()
    private val entryDao = database.entryDao()
    private val cardDao = database.creditCardDao()

    override fun observeAll(): Flow<List<Recurrence>> =
        recurrenceDao.observeAll().map { list -> list.map { it.toDomain() } }

    override suspend fun getById(id: Long): Recurrence? = recurrenceDao.getById(id)?.toDomain()

    override suspend fun add(recurrence: Recurrence, window: PredictionWindow): Long =
        database.withTransaction {
            val id = recurrenceDao.insert(recurrence.toEntity())
            predict(recurrence.copy(id = id), window.from, window.to)
            id
        }

    override suspend fun update(recurrence: Recurrence, window: PredictionWindow) = database.withTransaction {
        val previous = recurrenceDao.getById(recurrence.id)?.toDomain()
        recurrenceDao.update(recurrence.toEntity())
        // Upcoming predictions are rebuilt anyway; only what the user confirmed or skipped carries over.
        entryDao.deletePredictedFrom(recurrence.id, window.from)
        if (previous != null) carrySlots(previous, recurrence)
        entryDao.deletePredictedOutside(recurrence.id, recurrence.startsOn, recurrence.endsOn)
        rebuild(recurrence, window.from, window.to)
    }

    override suspend fun delete(recurrence: Recurrence, window: PredictionWindow) = database.withTransaction {
        entryDao.deletePredictedFrom(recurrence.id, window.from)
        recurrenceDao.delete(recurrence.toEntity())
    }

    override suspend fun applyToUpcoming(entry: Entry, window: PredictionWindow) = database.withTransaction {
        val recurrenceId = requireNotNull(entry.recurrenceId) { "entry was not generated by a recurrence" }
        val slot = requireNotNull(entry.scheduledFor)
        val current = recurrenceDao.getById(recurrenceId)?.toDomain()
        if (current == null) {
            // Deleted while the form was open: its entries were already detached (SET NULL).
            entryDao.update(entry.copy(recurrenceId = null, scheduledFor = null).toEntity())
            return@withTransaction
        }
        val recurrence = current.withValuesFrom(entry)
        entryDao.update(entry.toEntity())
        recurrenceDao.update(recurrence.toEntity())
        rebuild(recurrence, maxOf(slot.plusDays(1), window.from), window.to)
    }

    override suspend fun predictAll(window: PredictionWindow): Int = database.withTransaction {
        recurrenceDao.getAll().sumOf { predict(it.toDomain(), window.from, window.to) }
    }

    /** Moves used slots so they keep naming their payment under the new schedule (see carrySlotsFrom). */
    private suspend fun carrySlots(previous: Recurrence, recurrence: Recurrence) {
        val skips = recurrenceDao.skippedSlots(recurrence.id)
        val scheduled = entryDao.scheduledEntries(recurrence.id)
        val moves = recurrence.carrySlotsFrom(previous, skips + scheduled.mapNotNull { it.scheduledFor })
        if (moves.moved.isEmpty() && moves.skipped.isEmpty()) return
        val toMove = scheduled.filter { it.scheduledFor in moves.moved }
        // Two steps, since (recurrence, slot) is unique and a new slot may still be another's old one.
        entryDao.updateAll(toMove.map { it.copy(scheduledFor = null) })
        entryDao.updateAll(toMove.map { it.copy(scheduledFor = moves.moved.getValue(requireNotNull(it.scheduledFor))) })
        recurrenceDao.deleteSkips(recurrence.id)
        (skips.map { moves.moved[it] ?: it } + moves.skipped).toSet()
            .forEach { recurrenceDao.insertSkip(RecurrenceSkipEntity(recurrence.id, it)) }
    }

    private suspend fun rebuild(recurrence: Recurrence, from: LocalDate, to: LocalDate) {
        entryDao.deletePredictedFrom(recurrence.id, from)
        predict(recurrence, from, to)
    }

    private suspend fun predict(recurrence: Recurrence, from: LocalDate, to: LocalDate): Int {
        if (from.isAfter(to)) return 0
        val usedSlots = entryDao.scheduledDates(recurrence.id) + recurrenceDao.skippedSlots(recurrence.id)
        // Cannot be missing: a card used by a recurrence is never deleted (RESTRICT and the delete check).
        val card = recurrence.creditCardId?.let { requireNotNull(cardDao.getById(it)) { "recurrence card missing" }.toDomain() }
        val entries = recurrence.predictedEntriesBetween(from, to, usedSlots.toSet(), card)
        entryDao.insertAll(entries.map { it.toEntity() })
        return entries.size
    }
}
