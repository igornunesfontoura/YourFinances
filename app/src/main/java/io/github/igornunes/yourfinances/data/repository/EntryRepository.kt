package io.github.igornunes.yourfinances.data.repository

import androidx.room.withTransaction
import io.github.igornunes.yourfinances.data.db.AppDatabase
import io.github.igornunes.yourfinances.data.db.entity.RecurrenceSkipEntity
import io.github.igornunes.yourfinances.data.db.entity.toDomain
import io.github.igornunes.yourfinances.data.db.entity.toEntity
import io.github.igornunes.yourfinances.domain.model.DateBasis
import io.github.igornunes.yourfinances.domain.model.Entry
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map
import java.time.YearMonth

/** Entries as the UI sees them. */
interface EntryRepository {
    fun observeMonth(month: YearMonth, basis: DateBasis): Flow<List<Entry>> = observeMonths(month, month, basis)

    /** Entries of the months [first]..[last], inclusive. */
    fun observeMonths(first: YearMonth, last: YearMonth, basis: DateBasis): Flow<List<Entry>>

    suspend fun getById(id: Long): Entry?

    suspend fun add(entry: Entry): Long

    suspend fun update(entry: Entry)

    suspend fun delete(entry: Entry)
}

class RoomEntryRepository(private val database: AppDatabase) : EntryRepository {
    private val entryDao = database.entryDao()
    private val recurrenceDao = database.recurrenceDao()

    override fun observeMonths(first: YearMonth, last: YearMonth, basis: DateBasis): Flow<List<Entry>> {
        val from = first.atDay(1)
        val to = last.atEndOfMonth()
        val entities = when (basis) {
            DateBasis.ACCRUAL -> entryDao.observeOccurredBetween(from, to)
            DateBasis.CASH -> entryDao.observePaidBetween(from, to)
        }
        return entities.map { list -> list.map { it.toDomain() } }
    }

    override suspend fun getById(id: Long): Entry? = entryDao.getById(id)?.toDomain()

    override suspend fun add(entry: Entry): Long = entryDao.insert(entry.toEntity())

    override suspend fun update(entry: Entry) = entryDao.update(entry.toEntity())

    /** Deleting an entry generated by a recurrence skips its slot, so it is not generated again. */
    override suspend fun delete(entry: Entry) = database.withTransaction {
        if (entry.recurrenceId != null && entry.scheduledFor != null) {
            recurrenceDao.insertSkip(RecurrenceSkipEntity(entry.recurrenceId, entry.scheduledFor))
        }
        entryDao.delete(entry.toEntity())
    }
}
